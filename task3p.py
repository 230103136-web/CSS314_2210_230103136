import numpy as np
import numba as nb
import time
import os
import sys

student_id = 230103136
n = 2000000
cores = os.cpu_count() or 1

np.random.seed(student_id)
a = np.random.randint(1, 11, n).astype(np.int64)

nb.set_num_threads(min(cores, nb.config.NUMBA_NUM_THREADS))

@nb.njit
def serial_scan(a):
    out = np.empty_like(a)
    out[0] = a[0]
    for i in range(1, len(a)):
        out[i] = out[i-1] + a[i]
    return out

@nb.njit(parallel=True)
def parallel_scan(a, chunks):
    n = len(a)
    out = np.empty_like(a)
    sums = np.zeros(chunks, dtype=np.int64)
    size = (n + chunks - 1) // chunks


    for c in nb.prange(chunks):
        start = c * size
        end = min(start + size, n)
        s = 0
        for i in range(start, end):
            s += a[i]
            out[i] = s
        sums[c] = s


    offsets = np.zeros(chunks, dtype=np.int64)
    for c in range(1, chunks):
        offsets[c] = offsets[c-1] + sums[c-1]


    for c in nb.prange(chunks):
        start = c * size
        end = min(start + size, n)
        for i in range(start, end):
            out[i] += offsets[c]

    return out

serial_scan(a)
parallel_scan(a, cores)

start = time.perf_counter()
s = serial_scan(a)
t1 = (time.perf_counter() - start) * 1000

start = time.perf_counter()
p = parallel_scan(a, cores)
t2 = (time.perf_counter() - start) * 1000

try:
    assert p[-1] == s[-1]
    status = "PASS"
except AssertionError:
    status = "FAIL"

print("ID:", student_id)
print("Cores:", cores)
print("Serial:", round(t1, 2), "ms")
print("Parallel:", round(t2, 2), "ms")
print("Speedup:", round(t1 / t2, 2))
print("Verify:", status)

if status == "FAIL":
    sys.exit(1)