import random
import math
import time
import threading

student_id = 230103136
n = 40000000
threads = 4

shared_rng = random.Random(student_id)
lock = threading.Lock()

def shared_worker(count, results, idx):
    hits = 0
    for i in range(count):
        with lock:
            x = shared_rng.random()
            y = shared_rng.random()
        if x*x + y*y <= 1:
            hits += 1
    results[idx] = hits

def local_worker(count, results, idx):
    rng = random.Random(student_id * 10 + idx)
    hits = 0
    for i in range(count):
        x = rng.random()
        y = rng.random()
        if x*x + y*y <= 1:
            hits += 1
    results[idx] = hits

def run(worker):
    results = [0] * threads
    jobs = []
    start = time.perf_counter()

    for i in range(threads):
        t = threading.Thread(
            target=worker,
            args=(n // threads, results, i)
        )
        jobs.append(t)
        t.start()

    for t in jobs:
        t.join()

    ms = (time.perf_counter() - start) * 1000
    pi = 4 * sum(results) / n
    return pi, abs(pi - math.pi), ms

pi1, err1, t1 = run(shared_worker)
pi2, err2, t2 = run(local_worker)

print("ID:", student_id)
print("Threads:", threads)
print("Shared PI:", round(pi1, 6))
print("Shared Error:", round(err1, 6))
print("Shared Time:", round(t1, 2), "ms")
print("Local PI:", round(pi2, 6))
print("Local Error:", round(err2, 6))
print("Local Time:", round(t2, 2), "ms")
print("Speedup:", round(t1 / t2, 2))