import numpy as np
import numba as nb
import os
import time

student_id = 230103136
n = 8000

np.random.seed(student_id)
a = np.random.random((n, n)).astype(np.float64)

cores = os.cpu_count() or 1
threads = min(cores, nb.config.NUMBA_NUM_THREADS)
nb.set_num_threads(threads)

@nb.njit(parallel=True)
def row_sum(a):
    total = np.zeros(a.shape[0])
    for i in nb.prange(a.shape[0]):
        s = 0.0
        for j in range(a.shape[1]):
            s += a[i, j]
        total[i] = s
    return np.sum(total)

@nb.njit(parallel=True)
def col_sum(a):
    total = np.zeros(a.shape[1])
    for j in nb.prange(a.shape[1]):
        s = 0.0
        for i in range(a.shape[0]):
            s += a[i, j]
        total[j] = s
    return np.sum(total)

row_sum(a)
col_sum(a)

start = time.perf_counter()
x = row_sum(a)
t1 = (time.perf_counter() - start) * 1000

start = time.perf_counter()
y = col_sum(a)
t2 = (time.perf_counter() - start) * 1000

print("ID:", student_id)
print("Cores:", cores)
print("Threads:", nb.get_num_threads())
print("Row:", round(t1, 2), "ms")
print("Col:", round(t2, 2), "ms")
print("Penalty:", round(t2 / t1, 2))
print("Match:", np.isclose(x, y))