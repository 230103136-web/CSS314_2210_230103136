import hashlib
import time
import os
from concurrent.futures import ThreadPoolExecutor

student_id = 230103136
cores = os.cpu_count() or 1
tasks = 10000

data = str(student_id).encode().ljust(1024, b"x")

def work(i):
    x = data
    for j in range(500):
        x = hashlib.sha256(x).digest()
    return x

sizes = sorted(set([
    1, max(1, cores // 2), cores,
    cores * 2, cores * 4, cores * 16, 256
]))

times = []

for size in sizes:
    start = time.perf_counter()

    with ThreadPoolExecutor(max_workers=size) as pool:
        list(pool.map(work, range(tasks)))

    ms = (time.perf_counter() - start) * 1000
    times.append(ms)

base = times[0]

print("ID:", student_id)
print("Cores:", cores)
print("Pool | Time(ms) | Speedup | Status")

best = float("inf")
for size, ms in zip(sizes, times):
    speedup = base / ms

    if ms < best:
        status = "OK"
        best = ms
    else:
        status = "WORSE"

    print(size, "|", round(ms, 2), "|",
          round(speedup, 2), "|", status)