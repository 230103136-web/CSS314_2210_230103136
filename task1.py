import os
import platform
import time
import numpy as np

student_id = 230103136

print("Student ID:", student_id)
print("OS:", platform.system(), platform.release())
print("CPU:", platform.processor() or platform.machine())
print("Logical cores:", os.cpu_count())

np.random.seed(student_id)
data = np.random.random(20_000_000).astype(np.float64)

start = time.perf_counter()

total = 0.0
for x in data:
    total += x

mean = total / len(data)

variance = 0.0
for x in data:
    variance += (x - mean) ** 2

std = (variance / len(data)) ** 0.5

end = time.perf_counter()

print("Array size:", len(data))
print("Data type:", data.dtype)
print("Serial sum:", total)
print("Serial standard deviation:", std)
print("Execution time (ms):", (end - start) * 1000)